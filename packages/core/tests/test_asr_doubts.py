"""Фильтр шумных сомнений в распознавании (010 §6)."""

import pytest

from sobesnik_core.asr_doubts import filter_doubts, is_noisy


@pytest.mark.parametrize(
    "doubt",
    [
        "распознано «рак» — возможно, сказано «RAG»",
        "распознано «Селлари» — возможно, сказано «Sentry» или «Celery»",
        "распознано 'инио' — возможно, сказано '__init__'",
        'распознано "Jill" — возможно, сказано "GIL"',
        "распознано «викторизация» — возможно, сказано «векторизация»",
        "распознано «join load» — возможно, сказано «joinedload»",
        "распознано «считать весь индекс» — возможно, сказано «читать весь индекс»",
    ],
)
def test_recognition_slips_kept(doubt: str) -> None:
    assert not is_noisy(doubt)


@pytest.mark.parametrize(
    "doubt",
    [
        # перефраз, а не огрех распознавания
        "распознано «закрыт доступ» — возможно, сказано «скрыт от глаз»",
        "распознано «высокоуровнево» — возможно, сказано «сверху»",
        "распознано «полить» — возможно, сказано «показать» или «сказать»",
        # добавлено слово, искажения нет
        "распознано «хранить» — возможно, сказано «пароли хранить»",
        # просто написание кириллицей или слитно
        "распознано «джейсон» — возможно, сказано «JSON»",
        "распознано «постгрес» — возможно, сказано «PostgreSQL»",
        "распознано «асинк ай о» — возможно, сказано «asyncio»",
        "распознано 'skiplocked' — возможно, сказано 'SKIP LOCKED'",
    ],
)
def test_noise_dropped(doubt: str) -> None:
    assert is_noisy(doubt)


@pytest.mark.parametrize(
    "doubt",
    [
        "векторизация, видимо, тут про токены",
        "распознано «векторизация происходит» — контекст подразумевает токенизацию",
        "",
    ],
)
def test_unparsed_kept(doubt: str) -> None:
    assert not is_noisy(doubt)


def test_filter_keeps_order() -> None:
    doubts = [
        "распознано «рак» — возможно, сказано «RAG»",
        "распознано «закрыт доступ» — возможно, сказано «скрыт от глаз»",
        "распознано «гид» — возможно, сказано «git»",
    ]
    assert filter_doubts(doubts) == [doubts[0], doubts[2]]
